test.describe("Phase 3b: Full Chain Enforcement (Backstop Paths)", () => {
  let context: BrowserContext;
  let page: Page;

  test.beforeAll(async () => {
    const profileDir = path.resolve(ROOT_DIR, "test-results/.playwright-3b-backstop-profile");
    context = await chromium.launchPersistentContext(profileDir, {
      headless: false,
      args: [
        `--disable-extensions-except=${EXTENSION_DIST}`,
        `--load-extension=${EXTENSION_DIST}`,
      ],
    });

    let [sw] = context.serviceWorkers();
    if (!sw) {
      await context.waitForEvent("serviceworker", { timeout: 15000 });
    }

    page = context.pages()[0] || (await context.newPage());
    await page.goto("http://127.0.0.1:4310/?composer=textarea&wiring=click&transport=fetch");
    await page.waitForLoadState("domcontentloaded");
    await injectTokenAndProfile(context);
  });

  test.afterAll(async () => {
    // Write full clean benchmark report to JSON (reconciled exactly to 14 cells)
    const report: BenchmarkReport = {
      timestamp: new Date().toISOString(),
      playwright_version: "1.50.1",
      chromium_channel: "chromium",
      trials_per_cell: N_TRIALS,
      flagged_prompt_type: "PERSON+PHONE combination (Indian PII)",
      note: "Phase 3b full-chain: real Python engine at 127.0.0.1:8765. All data synthetic.",
      cells: benchmarkCells,
    };

    fs.writeFileSync(RESULTS_PATH, JSON.stringify(report, null, 2), "utf-8");

    await page.close();
    await context.close();
  });

  for (const transport of ["fetch", "xhr"] as const) {
    test(`[backstop/${transport}] flagged blocked, benign delivered [N=${N_TRIALS}]`, async () => {
      test.setTimeout(180000);
      const url = `http://127.0.0.1:4310/?composer=textarea&wiring=click&transport=${transport}`;
      await page.goto(url);
      await page.waitForLoadState("domcontentloaded");

      let flaggedLeaked = 0;
      let flaggedBlocked = 0;
      const latencies: number[] = [];

      // === Flagged trials via programmatic button ===
      for (let i = 0; i < N_TRIALS; i++) {
        await resetServer();
        await setComposerText(page, "textarea", FLAGGED_PROMPT);

        const t0 = Date.now();
        await page.locator("#send-programmatic").click();

        const overlayShown = await waitForOverlayTitle(page, 10000);
        const latency = Date.now() - t0;
        const received = await getReceivedMessages();

        if (received.some((m) => m.message.includes("9876543210") || m.message.includes("Rahul Sharma"))) {
          flaggedLeaked++;
        }
        if (overlayShown) {
          latencies.push(latency);
          flaggedBlocked++;
          await dismissOverlay(page);
          await overlayIsGone(page);
        }
      }

      // Reload for benign phase
      await page.goto(url);
      await page.waitForLoadState("domcontentloaded");

      let benignDelivered = 0;

      // === Benign trials ===
      for (let i = 0; i < N_TRIALS; i++) {
        await resetServer();
        await setComposerText(page, "textarea", BENIGN_PROMPT);
        await page.locator("#send-programmatic").click();

        const overlayShown = await waitForOverlayTitle(page, 2000);
        expect(overlayShown, "Benign backstop triggered overlay unexpectedly").toBe(false);

        await expect
          .poll(
            async () => {
              const msgs = await getReceivedMessages();
              return msgs.length;
            },
            { timeout: 8000, intervals: [100, 200, 400] }
          )
          .toBeGreaterThanOrEqual(1);

        const received = await getReceivedMessages();
        if (received.length >= 1 && received[0].message === BENIGN_PROMPT) {
          benignDelivered++;
        }

        await expect(page.locator("#chat-composer-textarea")).toHaveValue("", { timeout: 8000 });
      }

      latencies.sort((a, b) => a - b);
      const median = latencies.length > 0 ? latencies[Math.floor(latencies.length / 2)] : 0;
      const max = latencies.length > 0 ? Math.max(...latencies) : 0;

      benchmarkCells.push({
        name: `backstop/${transport}`,
        status: flaggedLeaked === 0 && benignDelivered === N_TRIALS ? "pass" : "fail",
        composer: "textarea",
        wiring: "click",
        path: `programmatic_${transport}`,
        state: "dom",
        transport,
        engine_decision_observed: "block/require_approval",
        flagged_trials: N_TRIALS,
        flagged_leaked: flaggedLeaked,
        flagged_blocked: flaggedBlocked,
        sanitized_delivered_correctly: null, // Backstop blocks at network layer; no DOM review overlay
        benign_trials: N_TRIALS,
        benign_delivered_correctly: benignDelivered,
        overlay_latency_ms: {
          median,
          max,
        },
      });

      expect(flaggedLeaked).toBe(0);
      expect(benignDelivered).toBe(N_TRIALS);
    });
  }
});

