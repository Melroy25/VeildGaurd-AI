async function resetServer(_request?: APIRequestContext): Promise<void> {
  const res = await fetch("http://127.0.0.1:4310/__test/reset", { method: "POST" });
  expect(res.ok).toBeTruthy();
}

async function getReceivedMessages(
  _request?: APIRequestContext
): Promise<Array<{ message: string; timestamp: string }>> {
  const res = await fetch("http://127.0.0.1:4310/__test/received");
  const data = (await res.json()) as { messages?: Array<{ message: string; timestamp: string }> };
  return data.messages ?? [];
}

async function setComposerText(
  page: Page,
  composer: "textarea" | "contenteditable",
  text: string
): Promise<void> {
  if (composer === "textarea") {
    await page.locator("#chat-composer-textarea").fill(text);
  } else {
    const el = page.locator("#chat-composer-editable");
    await el.click();
    await page.evaluate((val: string) => {
      const node = document.getElementById("chat-composer-editable");
      if (node) {
        node.innerText = val;
        node.dispatchEvent(new Event("input", { bubbles: true }));
      }
    }, text);
  }
}

async function waitForOverlayTitle(page: Page, timeoutMs = 8000): Promise<boolean> {
  try {
    await page.waitForFunction(
      () => {
        const host = document.getElementById("veilguard-overlay-host");
        if (!host?.shadowRoot) return false;
        const el =
          host.shadowRoot.getElementById("vg-overlay-title") ||
          host.shadowRoot.getElementById("vg-err-title");
        return el != null;
      },
      undefined,
      { timeout: timeoutMs }
    );
    return true;
  } catch {
    return false;
  }
}

async function dismissOverlay(page: Page): Promise<void> {
  const host = page.locator("#veilguard-overlay-host");
  const editBtn = host.locator("button.btn-edit, button.btn-cancel, button.btn-dismiss");
  if (await editBtn.first().isVisible({ timeout: 500 }).catch(() => false)) {
    await editBtn.first().click();
  } else {
    await page.keyboard.press("Escape");
  }
}

async function overlayIsGone(page: Page, timeoutMs = 4000): Promise<boolean> {
  try {
    await page.waitForFunction(
      () => {
        const host = document.getElementById("veilguard-overlay-host");
        if (!host?.shadowRoot) return true;
        return host.shadowRoot.querySelector(".backdrop") == null;
      },
      undefined,
      { timeout: timeoutMs }
    );
    return true;
  } catch {
    return false;
  }
}

async function injectTokenAndProfile(
  context: BrowserContext,
  token: string = E2E_TOKEN,
  profile: string = "company"
): Promise<void> {
  let [sw] = context.serviceWorkers();
  if (!sw) {
    sw = await context.waitForEvent("serviceworker", { timeout: 15000 });
  }
  await sw.evaluate(
    ({ t, p }) => {
      return new Promise<void>((resolve) => {
        chrome.storage.local.set({ vg_token: t, vg_profile: p }, () => resolve());
      });
    },
    { t: token, p: profile }
  );
}

type SubmitPath = "click" | "enter" | "requestSubmit";

async function triggerDomSubmission(
  page: Page,
  pathType: SubmitPath,
  composer: "textarea" | "contenteditable",
  wiring: "form" | "click"
): Promise<void> {
  if (pathType === "click") {
    await page.locator("#send-btn").click();
  } else if (pathType === "enter") {
    const selector = composer === "textarea" ? "#chat-composer-textarea" : "#chat-composer-editable";
    await page.locator(selector).press("Enter");
  } else {
    // requestSubmit path: only valid with form wiring
    if (wiring === "form") {
      await page.evaluate(() => {
        const form = document.getElementById("chat-form") as HTMLFormElement | null;
        const btn = document.getElementById("send-btn") as HTMLElement | null;
        if (form) {
          if (typeof form.requestSubmit === "function") {
            try {
              form.requestSubmit(btn || undefined);
            } catch {
              form.dispatchEvent(new Event("submit", { bubbles: true, cancelable: true }));
            }
          } else {
            form.dispatchEvent(new Event("submit", { bubbles: true, cancelable: true }));
          }
        }
      });
    } else {
      await page.locator("#send-btn").click();
    }
  }
}

