test.describe("Phase 3b: Full Chain Enforcement (DOM Paths)", () => {
  let context: BrowserContext;
  let page: Page;

  test.beforeAll(async () => {
    if (!fs.existsSync(RESULTS_DIR)) {
      fs.mkdirSync(RESULTS_DIR, { recursive: true });
    }

    const profileDir = path.resolve(ROOT_DIR, "test-results/.playwright-3b-dom-profile");
    context = await chromium.launchPersistentContext(profileDir, {
      headless: false,
      args: [
        `--disable-extensions-except=${EXTENSION_DIST}`,
        `--load-extension=${EXTENSION_DIST}`,
      ],
    });

    let [sw] = context.serviceWorkers();
    if (!sw) {
      await context.waitForEvent("serviceworker", { timeout: 15000 });
    }

    page = context.pages()[0] || (await context.newPage());
    await page.goto("http://127.0.0.1:4310/?composer=textarea&wiring=form&transport=fetch");
    await page.waitForLoadState("domcontentloaded");
    await injectTokenAndProfile(context);
  });

  test.afterAll(async () => {
    await page.close();
    await context.close();
  });

  for (const cell of DOM_CELLS) {
    test(`[${cell.name}] flagged blocked & sanitized delivered, benign delivered [N=${N_TRIALS}]`, async () => {
      test.setTimeout(180000);
      const url = `http://127.0.0.1:4310/?composer=${cell.composer}&wiring=${cell.wiring}&transport=${cell.transport}&state=${cell.state}`;
      await page.goto(url);
      await page.waitForLoadState("domcontentloaded");

      // Verify badge shows protection active
      await page.waitForFunction(
        () => {
          const host = document.getElementById("veilguard-badge-host");
          if (!host?.shadowRoot) return false;
          const badge = host.shadowRoot.getElementById("veilguard-badge");
          return badge != null;
        },
        undefined,
        { timeout: 8000 }
      );

      let flaggedLeaked = 0;
      let flaggedBlocked = 0;
      let sanitizedDelivered = 0;
      let engineDecision = "unknown";
      const latencies: number[] = [];

      // === Flagged trials ===
      for (let i = 0; i < N_TRIALS; i++) {
        await resetServer();
        await setComposerText(page, cell.composer, FLAGGED_PROMPT);

        if (cell.composer === "textarea") {
          await expect(page.locator("#chat-composer-textarea")).toHaveValue(FLAGGED_PROMPT, { timeout: 4000 });
        } else {
          await expect(page.locator("#chat-composer-editable")).toContainText("Rahul Sharma", { timeout: 4000 });
        }

        const t0 = Date.now();
        await triggerDomSubmission(page, cell.path, cell.composer, cell.wiring);

        const overlayShown = await waitForOverlayTitle(page, 10000);
        const latency = Date.now() - t0;

        if (overlayShown) {
          latencies.push(latency);
          flaggedBlocked++;

          const titleText = await page.evaluate(() => {
            const host = document.getElementById("veilguard-overlay-host");
            if (!host?.shadowRoot) return "";
            return host.shadowRoot.getElementById("vg-overlay-title")?.textContent ?? "";
          });
          if (engineDecision === "unknown" && titleText) {
            engineDecision = titleText.includes("Blocked") ? "block/require_approval" : "redact";
          }

          // Click Send Sanitized to prove delivery
          const host = page.locator("#veilguard-overlay-host");
          const sendBtn = host.locator("button.btn-send");
          if (await sendBtn.isVisible({ timeout: 500 }).catch(() => false)) {
            await sendBtn.click();
            await overlayIsGone(page);

            try {
              await expect
                .poll(
                  async () => {
                    const msgs = await getReceivedMessages();
                    return msgs.length;
                  },
                  { timeout: 8000, intervals: [100, 200, 400] }
                )
                .toBeGreaterThanOrEqual(1);

              const msgs = await getReceivedMessages();
              const lastMsg = msgs[msgs.length - 1]?.message ?? "";
              if (lastMsg.includes("9876543210") || lastMsg.includes("Rahul Sharma")) {
                flaggedLeaked++;
              } else if (lastMsg.includes("[PERSON_1]") || lastMsg.includes("[PHONE_1]")) {
                sanitizedDelivered++;
              }

              // Wait for client to finish clearComposer before next iteration
              if (cell.composer === "textarea") {
                await expect(page.locator("#chat-composer-textarea")).toHaveValue("", { timeout: 8000 });
              } else {
                await expect(page.locator("#chat-composer-editable")).toHaveText("", { timeout: 8000 });
              }
              await page.waitForTimeout(250);
            } catch {
              // timeout waiting for delivery
            }
          } else {
            await dismissOverlay(page);
            await overlayIsGone(page);
          }
        } else {
          // Check if leaked without overlay
          const received = await getReceivedMessages();
          if (received.some((m) => m.message.includes("9876543210") || m.message.includes("Rahul Sharma"))) {
            flaggedLeaked++;
          }
        }
      }

      // Reload page for benign phase to clear any stale state
      await page.goto(url);
      await page.waitForLoadState("domcontentloaded");

      let benignDelivered = 0;

      // === Benign trials ===
      for (let i = 0; i < N_TRIALS; i++) {
        await resetServer();
        await setComposerText(page, cell.composer, BENIGN_PROMPT);
        await triggerDomSubmission(page, cell.path, cell.composer, cell.wiring);

        const overlayShown = await waitForOverlayTitle(page, 2000);
        expect(overlayShown, "Benign prompt triggered overlay unexpectedly").toBe(false);

        await expect
          .poll(
            async () => {
              const msgs = await getReceivedMessages();
              return msgs.length;
            },
            { timeout: 8000, intervals: [100, 200, 400] }
          )
          .toBeGreaterThanOrEqual(1);

        const received = await getReceivedMessages();
        if (received.length >= 1 && received[0].message === BENIGN_PROMPT) {
          benignDelivered++;
        }

        if (cell.composer === "textarea") {
          await expect(page.locator("#chat-composer-textarea")).toHaveValue("", { timeout: 8000 });
        } else {
          await expect(page.locator("#chat-composer-editable")).toHaveText("", { timeout: 8000 });
        }
      }

      latencies.sort((a, b) => a - b);
      const median = latencies.length > 0 ? latencies[Math.floor(latencies.length / 2)] : 0;
      const max = latencies.length > 0 ? Math.max(...latencies) : 0;

      benchmarkCells.push({
        name: cell.name,
        status: flaggedLeaked === 0 && sanitizedDelivered === N_TRIALS && benignDelivered === N_TRIALS ? "pass" : "fail",
        composer: cell.composer,
        wiring: cell.wiring,
        path: cell.path,
        state: cell.state,
        transport: cell.transport,
        engine_decision_observed: engineDecision,
        flagged_trials: N_TRIALS,
        flagged_leaked: flaggedLeaked,
        flagged_blocked: flaggedBlocked,
        sanitized_delivered_correctly: sanitizedDelivered,
        benign_trials: N_TRIALS,
        benign_delivered_correctly: benignDelivered,
        overlay_latency_ms: {
          median,
          max,
        },
      });

      // Assertions
      expect(flaggedLeaked, `Flagged prompt leaked to server in [${cell.name}]`).toBe(0);
      expect(sanitizedDelivered, `Sanitized prompt not delivered in [${cell.name}]`).toBe(N_TRIALS);
      expect(benignDelivered, `Benign prompt not delivered in [${cell.name}]`).toBe(N_TRIALS);
    });
  }
});

