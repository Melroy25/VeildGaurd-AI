/**
 * VeilGuard AI - Phase 3b Full Chain Enforcement E2E Test Suite
 *
 * Tests the complete enforcement pipeline:
 *   Content Script (DOM interception)
 *     → Background Service Worker (engine-client.ts)
 *       → Local Python Engine (POST /analyze)
 *         → Review Overlay (showReviewOverlay / showEngineErrorOverlay)
 *
 * Benchmark matrix: 4 cells (2 composer × 2 wiring) × 3 DOM paths + 2 backstop paths.
 * Results written to bench/results/enforcement_full_chain_mock_site.json.
 *
 * Rule 10: All test prompts use strictly synthetic data — no real personal data.
 * Rule 1:  Benchmark JSON is generated by this test run — never hand-edited.
 *
 * Prerequisites:
 *   1. npm run build  (builds extension/dist/)
 *   2. Playwright webServer launches mock-site (4310) and engine (8765)
 *   3. Extension is loaded with token "e2e-test-token" matching VEILGUARD_TOKEN
 *
 * The options page token and profile are pre-set via chrome.storage.local
 * using page.evaluate() in beforeAll so the background has a valid token.
 */

import {
  test,
  expect,
  chromium,
  type BrowserContext,
  type Page,
  type APIRequestContext,
} from "@playwright/test";
import path from "path";
import { fileURLToPath } from "url";
import fs from "fs";

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);
const ROOT_DIR = path.resolve(__dirname, "../..");
const EXTENSION_DIST = path.resolve(ROOT_DIR, "extension/dist");
const RESULTS_DIR = path.resolve(ROOT_DIR, "bench/results");
const RESULTS_PATH = path.resolve(RESULTS_DIR, "enforcement_full_chain_mock_site.json");

/** Synthetic Indian PII prompt — contains PERSON + PHONE combination triggering require_approval */
const FLAGGED_PROMPT =
  "Analyze customer Rahul Sharma's account. His contact number is 9876543210 and transaction ID is TXN-9012.";

/** Benign prompt with no personal data — engine should return decision=allow */
const BENIGN_PROMPT = "Summarize the benefits of unit testing in three bullet points.";

/** E2E test bearer token — must match VEILGUARD_TOKEN env var in playwright.config.ts */
const E2E_TOKEN = process.env["VEILGUARD_TOKEN"] ?? "e2e-test-token";

const N_TRIALS = process.env["VG_TRIALS"] ? parseInt(process.env["VG_TRIALS"], 10) : 3;

// ---------------------------------------------------------------------------
// Result types
// ---------------------------------------------------------------------------

interface ResultCell {
  composer: "textarea" | "contenteditable";
  wiring: "form" | "click";
  path: "click" | "enter" | "submit" | "programmatic_fetch" | "programmatic_xhr";
  transport: "fetch" | "xhr";
  engine_decision_observed: string;
  flagged_trials: number;
  flagged_leaked: number;    // Flagged prompts that reached the mock server (must be 0)
  flagged_blocked: number;   // Flagged prompts that were blocked by VeilGuard
  benign_trials: number;
  benign_delivered_correctly: number;
}

interface BenchmarkReport {
  timestamp: string;
  playwright_version: string;
  chromium_channel: string;
  engine_token: string;
  trials_per_cell: number;
  flagged_prompt_type: string;
  note: string;
  cells: ResultCell[];
}

const benchmarkCells: ResultCell[] = [];

// ---------------------------------------------------------------------------
// Helpers
// ---------------------------------------------------------------------------

async function resetServer(request: APIRequestContext): Promise<void> {
  const res = await request.post("http://127.0.0.1:4310/__test/reset");
  expect(res.ok()).toBeTruthy();
}

async function getReceivedMessages(
  request: APIRequestContext
): Promise<Array<{ message: string; timestamp: string }>> {
  const res = await request.get("http://127.0.0.1:4310/__test/received");
  const data = await res.json() as { messages?: Array<{ message: string; timestamp: string }> };
  return data.messages ?? [];
}

async function setComposerText(
  page: Page,
  composer: "textarea" | "contenteditable",
  text: string
): Promise<void> {
  if (composer === "textarea") {
    await page.locator("#chat-composer-textarea").fill(text);
  } else {
    const el = page.locator("#chat-composer-editable");
    await el.click();
    await page.evaluate((val: string) => {
      const node = document.getElementById("chat-composer-editable");
      if (node) {
        node.innerText = val;
        node.dispatchEvent(new Event("input", { bubbles: true }));
      }
    }, text);
  }
}

async function waitForOverlayTitle(page: Page, timeoutMs = 8000): Promise<boolean> {
  try {
    // The review overlay title is inside Shadow DOM — query via shadowRoot
    await page.waitForFunction(
      () => {
        const host = document.getElementById("veilguard-overlay-host");
        if (!host?.shadowRoot) return false;
        const el = host.shadowRoot.getElementById("vg-overlay-title");
        return el != null && el.offsetParent != null;
      },
      { timeout: timeoutMs }
    );
    return true;
  } catch {
    return false;
  }
}

async function dismissOverlay(page: Page): Promise<void> {
  // Try both edit button (review overlay) and dismiss button (error overlay)
  await page.evaluate(() => {
    const host = document.getElementById("veilguard-overlay-host");
    if (!host?.shadowRoot) return;
    const editBtn = host.shadowRoot.querySelector("button.btn-edit") as HTMLButtonElement | null;
    const dismissBtn = host.shadowRoot.querySelector("button.btn-dismiss") as HTMLButtonElement | null;
    (editBtn ?? dismissBtn)?.click();
  });
}

async function injectTokenAndProfile(page: Page): Promise<void> {
  // Inject token + profile into chrome.storage.local via background
  // so the engine client has valid credentials for this test session
  await page.evaluate((token: string) => {
    return new Promise<void>((resolve) => {
      chrome.storage.local.set({ vg_token: token, vg_profile: "company" }, resolve);
    });
  }, E2E_TOKEN);
}

type SubmitPath = "click" | "enter" | "submit";

async function triggerDomSubmission(
  page: Page,
  pathType: SubmitPath,
  composer: "textarea" | "contenteditable",
  wiring: "form" | "click"
): Promise<void> {
  if (pathType === "click") {
    await page.locator("#send-btn").click();
  } else if (pathType === "enter") {
    const selector = composer === "textarea"
      ? "#chat-composer-textarea"
      : "#chat-composer-editable";
    await page.locator(selector).press("Enter");
  } else {
    // submit path: only valid with form wiring
    if (wiring === "form") {
      await page.evaluate(() => {
        const form = document.getElementById("chat-form") as HTMLFormElement | null;
        form?.dispatchEvent(new Event("submit", { bubbles: true, cancelable: true }));
      });
    } else {
      await page.locator("#send-btn").click();
    }
  }
}

// ---------------------------------------------------------------------------
// Test matrix configurations
// ---------------------------------------------------------------------------

const DOM_MATRIX = [
  { composer: "textarea" as const, wiring: "form" as const, transport: "fetch" as const },
  { composer: "textarea" as const, wiring: "click" as const, transport: "fetch" as const },
  { composer: "contenteditable" as const, wiring: "click" as const, transport: "fetch" as const },
];

const DOM_PATHS: SubmitPath[] = ["click", "enter", "submit"];

// ---------------------------------------------------------------------------
// Part A: DOM Interception with real engine
// ---------------------------------------------------------------------------

test.describe("Phase 3b: Full Chain Enforcement (DOM Paths)", () => {
  let context: BrowserContext;
  let page: Page;

  test.beforeAll(async () => {
    if (!fs.existsSync(RESULTS_DIR)) {
      fs.mkdirSync(RESULTS_DIR, { recursive: true });
    }

    const profileDir = path.resolve(ROOT_DIR, "test-results/.playwright-3b-dom-profile");
    context = await chromium.launchPersistentContext(profileDir, {
      headless: false,
      args: [
        `--disable-extensions-except=${EXTENSION_DIST}`,
        `--load-extension=${EXTENSION_DIST}`,
      ],
    });

    // Wait for extension service worker
    let [sw] = context.serviceWorkers();
    if (!sw) {
      await context.waitForEvent("serviceworker", { timeout: 15000 });
    }

    page = await context.newPage();

    // Navigate to mock site once to get extension content script context, then inject token
    await page.goto("http://127.0.0.1:4310/?composer=textarea&wiring=form&transport=fetch");
    await page.waitForLoadState("domcontentloaded");
    await injectTokenAndProfile(page);
  });

  test.afterAll(async () => {
    // Write or merge benchmark results
    let existing: Partial<BenchmarkReport> = {};
    try {
      existing = JSON.parse(fs.readFileSync(RESULTS_PATH, "utf-8")) as Partial<BenchmarkReport>;
    } catch {
      // Fresh file
    }

    const report: BenchmarkReport = {
      timestamp: new Date().toISOString(),
      playwright_version: "1.50.x",
      chromium_channel: "chromium",
      engine_token: "e2e-test-token",
      trials_per_cell: N_TRIALS,
      flagged_prompt_type: "PERSON+PHONE combination (Indian PII)",
      note: "Phase 3b full-chain: real Python engine at 127.0.0.1:8765. All data synthetic.",
      cells: [...benchmarkCells, ...(existing.cells ?? [])],
    };

    fs.writeFileSync(RESULTS_PATH, JSON.stringify(report, null, 2), "utf-8");

    await page.close();
    await context.close();
  });

  for (const config of DOM_MATRIX) {
    for (const pathType of DOM_PATHS) {
      // Skip submit path for click-wired configs (no form element)
      if (pathType === "submit" && config.wiring === "click") continue;

      test(`[${config.composer}/${config.wiring}/${pathType}] flagged blocked, benign delivered [N=${N_TRIALS}]`, async () => {
        const url = `http://127.0.0.1:4310/?composer=${config.composer}&wiring=${config.wiring}&transport=${config.transport}`;
        await page.goto(url);
        await page.waitForLoadState("domcontentloaded");

        // Verify badge shows protection active
        await page.waitForFunction(
          () => {
            const host = document.getElementById("veilguard-badge-host");
            if (!host?.shadowRoot) return false;
            const badge = host.shadowRoot.getElementById("veilguard-badge");
            return badge != null;
          },
          { timeout: 8000 }
        );

        let flaggedLeaked = 0;
        let flaggedBlocked = 0;
        let engineDecision = "unknown";

        // === Flagged trials ===
        for (let i = 0; i < N_TRIALS; i++) {
          await resetServer(page.request);
          await setComposerText(page, config.composer, FLAGGED_PROMPT);
          await triggerDomSubmission(page, pathType, config.composer, config.wiring);

          const overlayShown = await waitForOverlayTitle(page, 10000);

          const received = await getReceivedMessages(page.request);
          if (received.some((m) => m.message.includes("9876543210"))) {
            flaggedLeaked++;
          }

          if (overlayShown) {
            flaggedBlocked++;
            // Capture engine decision from overlay title text
            const titleText = await page.evaluate(() => {
              const host = document.getElementById("veilguard-overlay-host");
              if (!host?.shadowRoot) return "";
              return host.shadowRoot.getElementById("vg-overlay-title")?.textContent ?? "";
            });
            if (engineDecision === "unknown" && titleText) {
              engineDecision = titleText.includes("Blocked") ? "block/require_approval" : "redact";
            }
            await dismissOverlay(page);
            // Wait for overlay to disappear
            await page.waitForFunction(
              () => {
                const host = document.getElementById("veilguard-overlay-host");
                if (!host?.shadowRoot) return true;
                return host.shadowRoot.querySelector(".backdrop") == null;
              },
              { timeout: 3000 }
            );
          }
        }

        // Reload page for benign phase to clear any stale state
        await page.goto(url);
        await page.waitForLoadState("domcontentloaded");
        await injectTokenAndProfile(page);

        let benignDelivered = 0;

        // === Benign trials ===
        for (let i = 0; i < N_TRIALS; i++) {
          await resetServer(page.request);
          await setComposerText(page, config.composer, BENIGN_PROMPT);
          await triggerDomSubmission(page, pathType, config.composer, config.wiring);

          // Overlay must NOT appear for benign content
          const overlayShown = await waitForOverlayTitle(page, 2000);
          expect(overlayShown, "Benign prompt triggered overlay unexpectedly").toBe(false);

          // Server must receive the message
          await expect.poll(
            async () => {
              const msgs = await getReceivedMessages(page.request);
              return msgs.length;
            },
            { timeout: 8000, intervals: [100, 200, 500] }
          ).toBeGreaterThanOrEqual(1);

          const received = await getReceivedMessages(page.request);
          if (received.length >= 1 && received[0].message === BENIGN_PROMPT) {
            benignDelivered++;
          }

          // Wait for composer to be cleared (server response received)
          if (config.composer === "textarea") {
            await expect(page.locator("#chat-composer-textarea")).toHaveValue("", { timeout: 5000 });
          } else {
            await expect(page.locator("#chat-composer-editable")).toHaveText("", { timeout: 5000 });
          }
        }

        benchmarkCells.push({
          composer: config.composer,
          wiring: config.wiring,
          path: pathType,
          transport: config.transport,
          engine_decision_observed: engineDecision,
          flagged_trials: N_TRIALS,
          flagged_leaked: flaggedLeaked,
          flagged_blocked: flaggedBlocked,
          benign_trials: N_TRIALS,
          benign_delivered_correctly: benignDelivered,
        });

        // Assertions
        expect(flaggedLeaked, `Flagged prompt leaked to server in [${config.composer}/${pathType}]`).toBe(0);
        expect(benignDelivered, `Benign prompt not delivered in [${config.composer}/${pathType}]`).toBe(N_TRIALS);
      });
    }
  }
});

