test.describe("Phase 3b: Fail-Closed Verification (engine offline simulation)", () => {
  let context: BrowserContext;
  let page: Page;

  test.beforeAll(async () => {
    const profileDir = path.resolve(ROOT_DIR, "test-results/.playwright-3b-failclosed-profile");
    context = await chromium.launchPersistentContext(profileDir, {
      headless: false,
      args: [
        `--disable-extensions-except=${EXTENSION_DIST}`,
        `--load-extension=${EXTENSION_DIST}`,
      ],
    });

    let [sw] = context.serviceWorkers();
    if (!sw) {
      await context.waitForEvent("serviceworker", { timeout: 15000 });
    }

    page = await context.newPage();
    await page.goto("http://127.0.0.1:4310/?composer=textarea&wiring=form&transport=fetch");
    await page.waitForLoadState("domcontentloaded");

    // Set an INVALID token to simulate auth failure (engine rejects it)
    await page.evaluate(() => {
      return new Promise<void>((resolve) => {
        chrome.storage.local.set({ vg_token: "invalid-token-that-will-be-rejected", vg_profile: "company" }, resolve);
      });
    });
  });

  test.afterAll(async () => {
    await page.close();
    await context.close();
  });

  test("Submission is blocked when engine returns 401 (invalid token)", async () => {
    await resetServer(page.request);
    await setComposerText(page, "textarea", FLAGGED_PROMPT);
    await page.locator("#send-btn").click();

    // Should show engine error overlay (not review overlay)
    const overlayShown = await waitForOverlayTitle(page, 10000);
    expect(overlayShown, "Error overlay should appear when engine rejects token").toBe(true);

    // Server must NOT have received the message
    const received = await getReceivedMessages(page.request);
    expect(received.length, "No messages should reach server when blocked").toBe(0);

    await dismissOverlay(page);
  });
});
